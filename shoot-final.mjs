import { chromium } from 'playwright-core';
const BASE = 'http://localhost:4180';
const OUT = process.env.TMP + '/shots';
const email = `final${Date.now()}@example.com`;
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await ctx.newPage();
const errors = [];
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto(BASE + '/signup');
await page.fill('#name', 'Final Tester');
await page.fill('#email', email);
await page.fill('#password', 'Correct-horse-battery9');
await page.click('button[type=submit]');
await page.waitForTimeout(2200);
await page.goto(BASE + '/courses/python-programming/readiness');
await page.waitForSelector('text=Your projects', { timeout: 15000 });
await page.waitForTimeout(500);
await page.screenshot({ path: `${OUT}/60-readiness-projects.png`, fullPage: true });
console.log('ok', await page.title());
console.log('errors:', errors.length ? errors : 'none');
await browser.close();
